// A local slash command has to read the same in the Text view whichever way
// session-events learned about it: a tail of the transcript file, or the
// lobby's mod (ADR-0036). The two are fed differently. The file holds every
// row Claude writes; the mod is handed only the rows the engine raises
// session.append for, and for a manual /compact that is the bare "/compact"
// row and nothing after it (measured on Claude Code 2.1.296, 2026-10-11: the
// boundary, summary, caveat, command and receipt rows all reached the file
// and none reached the mod). Each case below gives the transcript lines and
// what the mod is actually sent for the same command, and the two must come
// out as the same events.

// tLine marshals one transcript record. json.Marshal rather than a literal,
// because a receipt carries raw SGR bytes.
func tLine(t *testing.T, rec map[string]any) string {
	t.Helper()
	b, err := json.Marshal(rec)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func tUser(t *testing.T, uuid, at string, isMeta bool, text string) string {
	return tLine(t, map[string]any{"type": "user", "uuid": uuid, "timestamp": at, "isMeta": isMeta,
		"message": map[string]any{"role": "user", "content": text}})
}

func tSystem(t *testing.T, uuid, at, subtype, content string) string {
	return tLine(t, map[string]any{"type": "system", "uuid": uuid, "timestamp": at, "subtype": subtype, "content": content})
}

func tSummary(t *testing.T, uuid, at string) string {
	return tLine(t, map[string]any{"type": "user", "uuid": uuid, "timestamp": at, "isCompactSummary": true,
		"isVisibleInTranscriptOnly": true,
		"message": map[string]any{"role": "user", "content": "This session is being continued from a previous conversation."}})
}

// modText is a row the way the mod forwards it: content as text blocks.
func modText(uuid, door, typ, name, role, text string, isMeta bool) ModEvent {
	b, _ := json.Marshal([]map[string]any{{"type": "text", "text": text}})
	return ModEvent{Type: ModRowEvent, T: 1791700000000, UUID: uuid, Door: door,
		Message: &ModMessage{Type: typ, Name: name, Role: role, IsMeta: isMeta, Content: b}}
}

func modLevel(compacting, running bool) ModEvent {
	return ModEvent{Type: ModLevelEvent, T: 1791700000000, Compacting: compacting, Running: running}
}

// shape is what a reader is shown: kinds, meta, bodies and turn boundaries,
// without the ids and times the two paths assign differently.
func shape(evs []Event) []string {
	out := make([]string, 0, len(evs))
	for _, e := range evs {
		s := string(e.Kind)
		if e.Kind == KindMeta {
			s += ":" + string(e.Meta)
		}
		if e.Body != "" && e.Kind != KindMeta {
			s += " " + e.Body
		}
		if e.Kind == KindMeta && e.Meta == MetaCommand {
			s += " " + e.Body
		}
		out = append(out, s+" @"+e.TurnID)
	}
	return out
}

const (
	stdoutCompacted = "<local-command-stdout>\x1b[2mCompacted (ctrl+o to see full summary)\x1b[22m</local-command-stdout>"
	caveatLine      = "<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.</local-command-caveat>"
	compactMarkup   = "<command-name>/compact</command-name>\n            <command-message>compact</command-message>\n            <command-args></command-args>"
)

type parityCase struct {
	name  string
	lines func(t *testing.T) []string
	// mod is what the engine hands the mod for the same command, in order.
	// A level event that ends a compaction is followed by the catch-up
	// session-events runs on that edge.
	mod []ModEvent
}

func parityCases() []parityCase {
	prior := func(t *testing.T) []string {
		return []string{
			tUser(t, "u1", "2026-10-11T07:00:00Z", false, "hello"),
			tReply("a1", "m1", "hi", "end_turn"),
		}
	}
	priorMod := []ModEvent{
		modText("u1", "prompt", "user", "", "user", "hello", false),
		// The mod reports the model off the turn's step, where the file has it
		// on the reply.
		{Type: ModModelEvent, T: 1791700000000, Model: "claude-opus-5-5"},
		modText("a1", "response", "assistant", "", "assistant", "hi", false),
		{Type: ModTurnEndEvent, T: 1791700000000},
	}
	return []parityCase{
		{
			name: "manual /compact",
			lines: func(t *testing.T) []string {
				return append(prior(t),
					tUser(t, "c0", "2026-10-11T07:01:35.842Z", false, "/compact"),
					tSystem(t, "b1", "2026-10-11T07:01:43.900Z", "compact_boundary", "Conversation compacted"),
					tSummary(t, "s1", "2026-10-11T07:01:43.901Z"),
					tUser(t, "k1", "2026-10-11T07:01:35.935Z", true, caveatLine),
					tUser(t, "n1", "2026-10-11T07:01:35.935Z", false, compactMarkup),
					tUser(t, "o1", "2026-10-11T07:01:43.943Z", false, stdoutCompacted),
				)
			},
			mod: append(append([]ModEvent{}, priorMod...),
				modText("c0", "prompt", "user", "", "user", "/compact", false),
				modLevel(true, false),
				modLevel(false, false),
			),
		},
		{
			name: "auto-compact inside a turn",
			lines: func(t *testing.T) []string {
				return append(prior(t),
					tUser(t, "u2", "2026-10-11T07:02:00Z", false, "keep going"),
					tSystem(t, "b2", "2026-10-11T07:02:01Z", "compact_boundary", "Conversation compacted"),
					tSummary(t, "s2", "2026-10-11T07:02:02Z"),
					tReply("a2", "m2", "done", "end_turn"),
				)
			},
			mod: append(append([]ModEvent{}, priorMod...),
				modText("u2", "prompt", "user", "", "user", "keep going", false),
				modLevel(true, true),
				modLevel(false, true),
				modText("a2", "response", "assistant", "", "assistant", "done", false),
				ModEvent{Type: ModTurnEndEvent, T: 1791700000000},
			),
		},
		{
			name: "/model answered as system rows",
			lines: func(t *testing.T) []string {
				return append(prior(t),
					tSystem(t, "m1x", "2026-10-11T07:03:00Z", "local_command",
						"<command-name>/model</command-name>\n            <command-message>model</command-message>\n            <command-args></command-args>"),
					tSystem(t, "m2x", "2026-10-11T07:03:01Z", "local_command",
						"<local-command-stdout>Kept model as `claude-opus-5-5`</local-command-stdout>"),
				)
			},
			mod: append(append([]ModEvent{}, priorMod...),
				modText("m1x", "command", "system", "local_command", "",
					"<command-name>/model</command-name>\n            <command-message>model</command-message>\n            <command-args></command-args>", false),
				modText("m2x", "command", "system", "local_command", "",
					"<local-command-stdout>Kept model as `claude-opus-5-5`</local-command-stdout>", false),
			),
		},
		{
			// Measured on 2.1.296 (2026-10-11): the engine appends all three
			// rows, the receipt as a system row and empty.
			name: "/clear",
			lines: func(t *testing.T) []string {
				return []string{
					tUser(t, "k3", "2026-10-11T07:38:50.199Z", true, caveatLine),
					tUser(t, "n3", "2026-10-11T07:38:50.293Z", false,
						"<command-name>/clear</command-name>\n            <command-message>clear</command-message>\n            <command-args></command-args>"),
					tSystem(t, "o3", "2026-10-11T07:38:50.320Z", "local_command", "<local-command-stdout></local-command-stdout>"),
				}
			},
			mod: []ModEvent{
				modText("k3", "command", "user", "", "user", caveatLine, true),
				modText("n3", "command", "user", "", "user",
					"<command-name>/clear</command-name>\n            <command-message>clear</command-message>\n            <command-args></command-args>", false),
				modText("o3", "command", "system", "local_command", "", "<local-command-stdout></local-command-stdout>", false),
			},
		},
	}
}

// fileShape is what a tail of the transcript shows for the lines.
func fileShape(t *testing.T, lines []string) []string {
	t.Helper()
	n := NewNormalizer("s")
	var out []Event
	for _, ln := range lines {
		out = append(out, n.Line([]byte(ln))...)
	}
	return shape(out)
}

// modShape is what the mod path shows: the mod's events fed in order, with the
// compaction catch-up run where session-events runs it.
func modShape(t *testing.T, path string, evs []ModEvent) []string {
	t.Helper()
	fs := NewModSource("s", path, nil)
	for _, ev := range evs {
		ended := fs.CompactionEnded(ev)
		fs.Feed(ev)
		if ended {
			if _, err := fs.CatchUpCompaction(ev.Running, 200*time.Millisecond); err != nil {
				t.Errorf("catch-up: %v", err)
			}
		}
	}
	return shape(fs.Replay(0))
}

func TestLocalCommandsReadTheSameOnBothPaths(t *testing.T) {
	for _, c := range parityCases() {
		t.Run(c.name, func(t *testing.T) {
			lines := c.lines(t)
			want := fileShape(t, lines)
			got := modShape(t, writeModTranscript(t, lines...), c.mod)
			if strings.Join(got, "\n") != strings.Join(want, "\n") {
				t.Errorf("mod path:\n  %s\nfile path:\n  %s", strings.Join(got, "\n  "), strings.Join(want, "\n  "))
			}
		})
	}
}

// Every local command's turn is settled by the time its receipt is in: the
// Working row never outlives the command.
func TestLocalCommandsLeaveNoTurnOpen(t *testing.T) {
	for _, c := range parityCases() {
		t.Run(c.name, func(t *testing.T) {
			lines := c.lines(t)
			fs := NewModSource("s", writeModTranscript(t, lines...), nil)
			for _, ev := range c.mod {
				ended := fs.CompactionEnded(ev)
				fs.Feed(ev)
				if ended {
					if _, err := fs.CatchUpCompaction(ev.Running, 200*time.Millisecond); err != nil {
						t.Errorf("catch-up: %v", err)
					}
				}
			}
			if fs.TurnOpen() {
				t.Errorf("mod path: a turn is still open after %s", c.name)
			}
			n := NewNormalizer("s")
			for _, ln := range lines {
				n.Line([]byte(ln))
			}
			if n.turnID != "" && !n.turnDone {
				t.Errorf("file path: a turn is still open after %s", c.name)
			}
		})
	}
}

// A compaction whose rows never reach the file in time still ends the turn
// the command opened, so the Working row stops.
func TestCompactCatchUpSettlesWhenTheRowsNeverArrive(t *testing.T) {
	p := writeModTranscript(t,
		tUser(t, "u1", "2026-10-11T07:00:00Z", false, "hello"),
		tReply("a1", "m1", "hi", "end_turn"),
		tUser(t, "c0", "2026-10-11T07:01:35Z", false, "/compact"),
	)
	fs := NewModSource("s", p, nil)
	for _, ev := range []ModEvent{
		modText("u1", "prompt", "user", "", "user", "hello", false),
		modText("a1", "response", "assistant", "", "assistant", "hi", false),
		{Type: ModTurnEndEvent, T: 1791700000000},
		modText("c0", "prompt", "user", "", "user", "/compact", false),
		modLevel(true, false),
	} {
		fs.CompactionEnded(ev)
		fs.Feed(ev)
	}
	end := modLevel(false, false)
	if !fs.CompactionEnded(end) {
		t.Fatal("compacting true then false is not an edge")
	}
	got, err := fs.CatchUpCompaction(false, 50*time.Millisecond)
	if err == nil {
		t.Errorf("catch-up found rows the file does not hold: %+v", got)
	}
	if !got.Settled {
		t.Error("the /compact turn was not settled")
	}
	if fs.TurnOpen() {
		t.Error("a turn is still open")
	}
}

// A prompt sent while the catch-up waits opens a turn of its own, and the
// fallback settles only the /compact turn, never that one.
func TestCompactCatchUpLeavesALaterTurnOpen(t *testing.T) {
	p := writeModTranscript(t, tUser(t, "c0", "2026-10-11T07:01:35Z", false, "/compact"))
	fs := NewModSource("s", p, nil)
	fs.Feed(modText("c0", "prompt", "user", "", "user", "/compact", false))
	fs.Feed(modLevel(true, false))
	go func() {
		time.Sleep(100 * time.Millisecond)
		fs.Feed(modText("u9", "prompt", "user", "", "user", "next question", false))
	}()
	if _, err := fs.CatchUpCompaction(false, 300*time.Millisecond); err == nil {
		t.Error("catch-up found rows the file does not hold")
	}
	if !fs.TurnOpen() || fs.TurnID() != "t2" {
		t.Errorf("turn %q open %v; want t2, the later prompt's, still open", fs.TurnID(), fs.TurnOpen())
	}
}

// The rows come in a batch Claude writes every 100 ms, so the receipt can
// land after the edge.
func TestCompactCatchUpWaitsForTheReceipt(t *testing.T) {
	lines := []string{
		tUser(t, "u1", "2026-10-11T07:00:00Z", false, "hello"),
		tReply("a1", "m1", "hi", "end_turn"),
		tUser(t, "c0", "2026-10-11T07:01:35Z", false, "/compact"),
	}
	p := writeModTranscript(t, lines...)
	fs := NewModSource("s", p, nil)
	for _, ev := range []ModEvent{
		modText("u1", "prompt", "user", "", "user", "hello", false),
		modText("a1", "response", "assistant", "", "assistant", "hi", false),
		{Type: ModTurnEndEvent, T: 1791700000000},
		modText("c0", "prompt", "user", "", "user", "/compact", false),
		modLevel(true, false),
		modLevel(false, false),
	} {
		fs.Feed(ev)
	}
	go func() {
		time.Sleep(200 * time.Millisecond)
		appendTranscript(t, p,
			tSystem(t, "b1", "2026-10-11T07:01:43Z", "compact_boundary", "Conversation compacted"),
			tSummary(t, "s1", "2026-10-11T07:01:43Z"),
			tUser(t, "o1", "2026-10-11T07:01:44Z", false, stdoutCompacted),
		)
	}()
	got, err := fs.CatchUpCompaction(false, 2*time.Second)
	if err != nil {
		t.Fatalf("catch-up: %v", err)
	}
	if got.Rows != 3 {
		t.Errorf("rows = %d, want 3", got.Rows)
	}
	kinds := modKinds(fs.Replay(0))
	if !strings.Contains(strings.Join(kinds, ","), "meta:compact") {
		t.Errorf("no compaction marker: %v", kinds)
	}
	if fs.TurnOpen() {
		t.Error("a turn is still open")
	}
}

// Rows the mod already sent are not drawn twice, and rows the catch-up drew
// are dropped when a mod copy arrives later.
func TestCompactCatchUpDrawsEachRowOnce(t *testing.T) {
	lines := []string{
		tUser(t, "c0", "2026-10-11T07:01:35Z", false, "/compact"),
		tSystem(t, "b1", "2026-10-11T07:01:43Z", "compact_boundary", "Conversation compacted"),
		tSummary(t, "s1", "2026-10-11T07:01:43Z"),
		tUser(t, "o1", "2026-10-11T07:01:44Z", false, stdoutCompacted),
	}
	fs := NewModSource("s", writeModTranscript(t, lines...), nil)
	fs.Feed(modText("c0", "prompt", "user", "", "user", "/compact", false))
	fs.Feed(modLevel(true, false))
	if _, err := fs.CatchUpCompaction(false, 200*time.Millisecond); err != nil {
		t.Fatal(err)
	}
	before := len(fs.Replay(0))
	fs.Feed(modText("o1", "command", "user", "", "user", stdoutCompacted, false))
	if after := len(fs.Replay(0)); after != before {
		t.Errorf("a late mod copy of a caught-up row drew again: %d events, then %d", before, after)
	}
}
