/**
 * Renders src/rpc/stubs.ts: every RPC of the pinned WsRpcGroup that
 * servedHandlers (src/rpc/handlers.ts) does not answer, mapped to its
 * fallback. scripts/gen-stubs.sh writes the result; test/stubs.test.ts checks
 * the committed file still equals it, so a pin bump that adds or removes an
 * RPC fails until the table is regenerated.
 */
import { WsRpcGroup } from "@t3tools/contracts";
import * as RpcSchema from "effect/rpc/RpcSchema";

import { type ConnectionContext, servedHandlers } from "../src/rpc/handlers.ts";

/**
 * A context that refuses to be read. servedHandlers must build its object
 * without touching the context; this makes a handler that does fail here
 * instead of quietly reading undefined.
 */
const NO_CONTEXT = new Proxy(
  {},
  {
    get(_target, property) {
      throw new Error(
        `servedHandlers read context.${String(property)} while building; read it inside the handler`,
      );
    },
  },
) as ConnectionContext;

export function servedTags(): ReadonlySet<string> {
  return new Set(Object.keys(servedHandlers(NO_CONTEXT)));
}

export interface RpcShape {
  readonly tag: string;
  readonly stream: boolean;
}

export function pinnedRpcs(): ReadonlyArray<RpcShape> {
  return [...WsRpcGroup.requests].map(([tag, rpc]) => ({
    tag,
    stream: RpcSchema.isStreamSchema(rpc.successSchema),
  }));
}

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;

export function renderStubs(rpcs: ReadonlyArray<RpcShape>, served: ReadonlySet<string>): string {
  const stubbed = rpcs.filter((rpc) => !served.has(rpc.tag));
  const lines = stubbed.map(({ tag, stream }) => {
    const key = IDENTIFIER.test(tag) ? tag : JSON.stringify(tag);
    return `  ${key}: ${stream ? "silentStream" : "unavailable"},`;
  });
  return `/**
 * Generated by scripts/gen-stubs.sh from the pinned WsRpcGroup. Do not edit.
 *
 * The ${stubbed.length} RPCs of ${rpcs.length} that the sidecar does not serve
 * (src/rpc/handlers.ts servedHandlers answers the rest), each mapped to its
 * fallback (src/rpc/fallback.ts). A pin bump that adds an RPC is a type error
 * in handlers.ts until this file is regenerated.
 */
import { silentStream, unavailable } from "./fallback.ts";

export const STUB_HANDLERS = {
${lines.join("\n")}
};
`;
}
